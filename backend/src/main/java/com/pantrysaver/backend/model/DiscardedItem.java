package com.pantrysaver.backend.model;

import java.time.LocalDateTime;
import java.util.UUID;

import jakarta.persistence.*;

@Entity
@Table(name = "discarded_items")

public class DiscardedItem {
  
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "household_id", nullable = false)
    private UUID householdId;

    @Column(name = "item_name", nullable = false)
    private String itemName;

    @Column(name = "quantity_discarded", nullable = false)
    private double quantity_discarded;

    @Column(name = "category")
    private String category;

    @Column(name = "logged_at", nullable = false)
    private LocalDateTime loggedAt;

    // JPA required
    public DiscardedItem() {}

    // constructor
    public DiscardedItem(
            UUID householdId,
            String itemName,
            double quantity_discarded,
            String category
    ) {
        this.householdId = householdId;
        this.itemName = itemName;
        this.quantity_discarded = quantity_discarded;
        this.category = category;
        this.loggedAt = LocalDateTime.now();
    }

    public UUID getId() {
        return id;
    }

    public UUID getHouseholdId() {
        return householdId;
    }

    public String getItemName() {
        return itemName;
    }

    public double getQuantity_Discarded() {
        return quantity_discarded;
    }

    public String getCategory() {
        return category;
    }

    public LocalDateTime getLoggedAt() {
        return loggedAt;
    }

    // no setter for ID because its generated by the db
    // and assigned in the service class

    public void setItemName(String itemName) {
        this.itemName = itemName;
    }

    public void setQuantity_Discarded(double quantity_discarded) {
        if (quantity_discarded < 0) {
            throw new IllegalArgumentException(
                "Quantity cannot be negative"
            );
        }
        this.quantity_discarded = quantity_discarded;
    }

    public void setCategory(String category) {
        this.category = category;
    }
  
}
